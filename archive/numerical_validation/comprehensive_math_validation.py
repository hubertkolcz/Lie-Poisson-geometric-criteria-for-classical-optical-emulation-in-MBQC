def create_cz_generator(q1, q2, n_qubits):
    """CZ Hamiltonian generator."""
    # CZ = exp(-iπ/4 (I - Z₁ - Z₂ + Z₁Z₂))
    # Generator ∝ (I - Z₁ - Z₂ + Z₁Z₂)
    ops_I = [I2] * n_qubits
    I_full = kron_list(ops_I)
    
    ops_Z1 = [I2] * n_qubits
    ops_Z1[q1] = Z
    Z1 = kron_list(ops_Z1)
    
    ops_Z2 = [I2] * n_qubits
    ops_Z2[q2] = Z
    Z2 = kron_list(ops_Z2)
    
    Z1Z2 = Z1 @ Z2
    
    return 1j * (I_full - Z1 - Z2 + Z1Z2) / 4

