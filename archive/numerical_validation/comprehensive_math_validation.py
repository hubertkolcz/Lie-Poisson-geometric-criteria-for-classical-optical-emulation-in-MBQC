def kron_list(ops):
    """Tensor product of list of operators."""
    result = ops[0]
    for op in ops[1:]:
        result = np.kron(result, op)
    return result

def commutator(A, B):
    """Lie bracket [A,B] = AB - BA."""
    return A @ B - B @ A

def anticommutator(A, B):
    """Anticommutator {A,B} = AB + BA."""
    return A @ B + B @ A

def trace_inner_product(A, B):
    """Hilbert-Schmidt inner product: Tr(A†B)."""
    return np.trace(A.conj().T @ B)

def is_hermitian(A, tol=1e-10):
    """Check if matrix is Hermitian."""
    return np.allclose(A, A.conj().T, atol=tol)

def is_unitary(U, tol=1e-10):
    """Check if matrix is unitary."""
    n = U.shape[0]
    return np.allclose(U @ U.conj().T, np.eye(n), atol=tol)

def is_linearly_independent(new_op, basis, tol=1e-10):
    """Check if operator is linearly independent of basis."""
    if len(basis) == 0:
        return np.linalg.norm(new_op) > tol
    
    new_vec = new_op.flatten()
    basis_matrix = np.array([b.flatten() for b in basis]).T
    coeffs, residuals, rank, s = np.linalg.lstsq(basis_matrix, new_vec, rcond=None)
    projection = basis_matrix @ coeffs
    residual = np.linalg.norm(new_vec - projection)
    return residual > tol

def compute_lie_algebra_dimension(generators, max_iter=50, tol=1e-10):
    """
    Compute dimension of Lie algebra generated by operators.
    Uses commutator closure algorithm.
    """
    basis = []
    for g in generators:
        g_traceless = g - np.trace(g) / g.shape[0] * np.eye(g.shape[0], dtype=complex)
        if np.linalg.norm(g_traceless) > tol:
            if is_linearly_independent(g_traceless, basis, tol):
                basis.append(g_traceless)
    
    for iteration in range(max_iter):
        new_elements = []
        n = len(basis)
        
        for i in range(n):
            for j in range(i + 1, n):
                comm = commutator(basis[i], basis[j])
                if np.linalg.norm(comm) > tol:
                    if is_linearly_independent(comm, basis + new_elements, tol):
                        new_elements.append(comm)
        
        if len(new_elements) == 0:
            break
        
        basis.extend(new_elements)
        
        if len(basis) > 300:
            break
    
    return len(basis)

