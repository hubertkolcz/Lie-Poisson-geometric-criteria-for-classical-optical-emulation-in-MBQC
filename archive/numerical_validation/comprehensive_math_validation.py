def create_cluster_state(edges, n_qubits):
    """Create cluster state from graph."""
    # Start with |+⟩^⊗n
    plus = np.array([1, 1], dtype=complex) / np.sqrt(2)
    state = plus
    for _ in range(n_qubits - 1):
        state = np.kron(state, plus)
    
    # Apply CZ on edges
    CZ = np.diag([1, 1, 1, -1]).astype(complex)
    for (i, j) in edges:
        state = apply_two_qubit_gate(state, CZ, i, j, n_qubits)
    
    return state

def apply_two_qubit_gate(state, gate, q1, q2, n_qubits):
    """Apply 2-qubit gate to state vector."""
    dim = 2 ** n_qubits
    new_state = np.zeros(dim, dtype=complex)
    
    for idx in range(dim):
        # Extract bits
        bits = [(idx >> (n_qubits - 1 - k)) & 1 for k in range(n_qubits)]
        b1, b2 = bits[q1], bits[q2]
        
        # Apply gate
        for b1_new in range(2):
            for b2_new in range(2):
                gate_elem = gate[b1_new * 2 + b2_new, b1 * 2 + b2]
                if abs(gate_elem) > 1e-10:
                    new_bits = bits.copy()
                    new_bits[q1] = b1_new
                    new_bits[q2] = b2_new
                    new_idx = sum(new_bits[k] << (n_qubits - 1 - k) for k in range(n_qubits))
                    new_state[new_idx] += gate_elem * state[idx]
    
    return new_state

