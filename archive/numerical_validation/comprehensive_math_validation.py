def hamming_distance_to_affine(f_values):
    """
    Compute minimum Hamming distance to affine functions.
    f_values: truth table as numpy array
    """
    n = int(np.log2(len(f_values)))
    N = 2**n
    
    # Generate all affine functions on n bits
    min_dist = N
    
    # Affine functions: a·x + b where a ∈ {0,1}^n, b ∈ {0,1}
    for a in range(N):  # Linear coefficient
        for b in range(2):  # Constant
            # Compute affine function
            affine_values = np.zeros(N, dtype=int)
            for x in range(N):
                # a·x is parity of a AND x
                ax = bin(a & x).count('1') % 2
                affine_values[x] = ax ^ b
            
            dist = np.sum(f_values != affine_values)
            min_dist = min(min_dist, dist)
    
    return min_dist

