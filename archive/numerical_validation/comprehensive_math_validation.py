def poisson_bracket_su2(f_grad, g_grad, s_vec):
    """
    Lie-Poisson bracket on su(2)*:
    {f, g}(μ) = ⟨μ, [df, dg]⟩
    
    For coordinate functions: {S_i, S_j} = ε_ijk S_k
    """
    # ε tensor
    epsilon = np.zeros((3, 3, 3))
    epsilon[0, 1, 2] = epsilon[1, 2, 0] = epsilon[2, 0, 1] = 1
    epsilon[0, 2, 1] = epsilon[2, 1, 0] = epsilon[1, 0, 2] = -1
    
    result = 0
    for k in range(3):
        for i in range(3):
            for j in range(3):
                result += s_vec[k] * epsilon[k, i, j] * f_grad[i] * g_grad[j]
    return result

