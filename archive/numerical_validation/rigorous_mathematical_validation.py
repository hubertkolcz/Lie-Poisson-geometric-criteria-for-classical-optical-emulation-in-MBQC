def compute_structure_constants(basis):
    """
    Compute structure constants f^k_ij where [e_i, e_j] = sum_k f^k_ij e_k.
    
    This identifies the Lie algebra type.
    """
    n = len(basis)
    if n == 0:
        return None
    
    structure_constants = np.zeros((n, n, n), dtype=complex)
    
    for i in range(n):
        for j in range(n):
            comm = commutator(basis[i], basis[j])
            
            # Express [e_i, e_j] in terms of basis
            comm_vec = comm.flatten()
            basis_matrix = np.array([b.flatten() for b in basis]).T
            
            coeffs, _, _, _ = np.linalg.lstsq(basis_matrix, comm_vec, rcond=None)
            structure_constants[i, j, :] = coeffs
    
    return structure_constants


def identify_lie_algebra(dim, structure_constants):
    """
    Identify the Lie algebra from its dimension and structure constants.
    
    Known algebras:
    - dim=3, [e1,e2]=e3 cyclic: so(3) ≅ su(2)
    - dim=n²-1, specific structure: su(n)
    - Abelian (all f=0): commutative
    """
    if structure_constants is None:
        return "trivial"
    
    # Check if abelian
    if np.allclose(structure_constants, 0):
        return f"abelian (dim={dim})"
    
    # Check for so(3) structure (dim=3)
    if dim == 3:
        # so(3) has f^k_ij = ε_ijk (Levi-Civita)
        return "so(3) ≅ su(2)"
    
    # Check for su(n) by dimension
    for n in range(2, 10):
        if dim == n*n - 1:
            return f"su({n})"
    
    # General case
    return f"Lie algebra (dim={dim})"


def check_semisimplicity(structure_constants):
    """
    Check if Lie algebra is semisimple via Killing form.
    
    Killing form: K(X,Y) = Tr(ad_X ∘ ad_Y)
    Algebra is semisimple iff K is non-degenerate.
    """
    if structure_constants is None:
        return False, None
    
    n = structure_constants.shape[0]
    
    # Compute Killing form matrix
    killing = np.zeros((n, n), dtype=complex)
    for i in range(n):
        for j in range(n):
            # ad_i has matrix (ad_i)^k_j = f^k_ij
            ad_i = structure_constants[i, :, :]
            ad_j = structure_constants[j, :, :]
            killing[i, j] = np.trace(ad_i @ ad_j)
    
    # Check non-degeneracy
    det = np.linalg.det(killing)
    is_semisimple = np.abs(det) > 1e-10
    
    return is_semisimple, killing


