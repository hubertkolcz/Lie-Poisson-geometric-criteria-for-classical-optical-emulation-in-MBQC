def create_pauli_basis():
    """
    Create Pauli matrices from mathematical definition.
    
    Definition: σ_x, σ_y, σ_z satisfy [σ_i, σ_j] = 2i ε_ijk σ_k
    These form a basis for su(2).
    """
    I = np.array([[1, 0], [0, 1]], dtype=complex)
    X = np.array([[0, 1], [1, 0]], dtype=complex)
    Y = np.array([[0, -1j], [1j, 0]], dtype=complex)
    Z = np.array([[1, 0], [0, -1]], dtype=complex)
    return {'I': I, 'X': X, 'Y': Y, 'Z': Z}


def verify_su2_algebra():
    """
    Verify that Pauli matrices satisfy su(2) commutation relations.
    [σ_i, σ_j] = 2i ε_ijk σ_k
    
    Returns computed structure constants.
    """
    paulis = create_pauli_basis()
    X, Y, Z = paulis['X'], paulis['Y'], paulis['Z']
    
    # Compute commutators
    comm_XY = X @ Y - Y @ X  # Should be 2i*Z
    comm_YZ = Y @ Z - Z @ Y  # Should be 2i*X
    comm_ZX = Z @ X - X @ Z  # Should be 2i*Y
    
    # Extract structure constants by comparing
    def extract_coefficient(comm, target):
        """Find c such that comm ≈ c * target"""
        # Use Frobenius inner product
        return np.trace(comm @ target.conj().T) / np.trace(target @ target.conj().T)
    
    f_XY_Z = extract_coefficient(comm_XY, Z)
    f_YZ_X = extract_coefficient(comm_YZ, X)
    f_ZX_Y = extract_coefficient(comm_ZX, Y)
    
    return {
        '[X,Y] coefficient of Z': f_XY_Z,
        '[Y,Z] coefficient of X': f_YZ_X,
        '[Z,X] coefficient of Y': f_ZX_Y,
        'expected (2i)': 2j,
        'su(2)_verified': np.allclose([f_XY_Z, f_YZ_X, f_ZX_Y], [2j, 2j, 2j])
    }


