def create_so3_generators():
    """
    Create so(3) generators (angular momentum / Stokes vector rotations).
    
    For Mueller matrices on Poincaré sphere.
    [L_i, L_j] = ε_ijk L_k
    """
    # Standard so(3) basis
    L_x = np.array([[0, 0, 0], [0, 0, -1], [0, 1, 0]], dtype=complex)
    L_y = np.array([[0, 0, 1], [0, 0, 0], [-1, 0, 0]], dtype=complex)
    L_z = np.array([[0, -1, 0], [1, 0, 0], [0, 0, 0]], dtype=complex)
    
    return [L_x, L_y, L_z]


def create_u1_generator():
    """
    Create u(1) generator (phase).
    
    For path-encoding phase shifts.
    """
    return [np.array([[1j]], dtype=complex)]


