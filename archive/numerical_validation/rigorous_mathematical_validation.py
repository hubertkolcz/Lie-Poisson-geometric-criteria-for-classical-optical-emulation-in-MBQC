def compute_quadratic_casimir(basis):
    """
    Compute quadratic Casimir element C = sum_ij g^ij e_i e_j
    where g^ij is the inverse Killing form.
    
    For su(2): C = S_x² + S_y² + S_z² (angular momentum squared)
    """
    if len(basis) == 0:
        return None
    
    # Compute Killing form
    structure_constants = compute_structure_constants(basis)
    is_ss, killing = check_semisimplicity(structure_constants)
    
    if not is_ss:
        return None  # No Casimir for non-semisimple
    
    # Inverse Killing form
    try:
        killing_inv = np.linalg.inv(killing)
    except:
        return None
    
    # Casimir = sum_ij g^ij e_i e_j (in representation)
    dim = basis[0].shape[0]
    casimir = np.zeros((dim, dim), dtype=complex)
    
    for i in range(len(basis)):
        for j in range(len(basis)):
            casimir += killing_inv[i, j] * (basis[i] @ basis[j])
    
    return casimir


def verify_casimir_commutes(casimir, basis):
    """
    Verify that Casimir commutes with all algebra elements.
    
    [C, e_i] = 0 for all i (definition of Casimir)
    """
    if casimir is None:
        return False, []
    
    commutators = []
    for i, e in enumerate(basis):
        comm = commutator(casimir, e)
        comm_norm = np.linalg.norm(comm)
        commutators.append(comm_norm)
    
    all_commute = all(c < 1e-8 for c in commutators)
    return all_commute, commutators


def count_casimirs_by_rank(dim_algebra, dim_representation):
    """
    For simple Lie algebras, number of independent Casimirs = rank.
    
    Ranks:
    - su(n): rank = n-1
    - so(n): rank = floor(n/2)
    """
    # Infer from dimension
    for n in range(2, 20):
        if dim_algebra == n*n - 1:  # su(n)
            return n - 1, f"su({n})"
    
    return 1, "unknown"


