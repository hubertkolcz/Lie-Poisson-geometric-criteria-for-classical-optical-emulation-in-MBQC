def check_liouville_integrability(dim_algebra, n_casimirs, phase_space_dim):
    """
    Check Liouville integrability condition.
    
    System is integrable if:
    - Number of independent Casimirs >= dim(phase_space)/2
    
    For quantum: phase_space_dim = 2 * (dim_H - 1) for pure states
    """
    required_casimirs = phase_space_dim // 2
    is_integrable = n_casimirs >= required_casimirs
    
    return {
        'dim_algebra': dim_algebra,
        'n_casimirs': n_casimirs,
        'phase_space_dim': phase_space_dim,
        'required_for_integrability': required_casimirs,
        'is_integrable': is_integrable
    }


