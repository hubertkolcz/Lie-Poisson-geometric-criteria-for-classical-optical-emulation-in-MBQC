def create_mbqc_generators_pauli_only(n_qubits):
    """
    Create MBQC generators: single-qubit Paulis only.
    
    These generate local operations on each qubit.
    g = <iσ_x^(k), iσ_y^(k), iσ_z^(k) : k=1..n>
    """
    paulis = create_pauli_basis()
    I, X, Y, Z = paulis['I'], paulis['X'], paulis['Y'], paulis['Z']
    
    generators = []
    for q in range(n_qubits):
        for P in [X, Y, Z]:
            # Create I ⊗ ... ⊗ P ⊗ ... ⊗ I
            ops = [I] * n_qubits
            ops[q] = P
            generators.append(1j * kron_n(ops))
    
    return generators


def create_cz_hamiltonian(q1, q2, n_qubits):
    """
    Create CZ gate Hamiltonian.
    
    CZ = |00><00| + |01><01| + |10><10| - |11><11|
       = exp(-i π/4 (I - Z_1)(I - Z_2))
    
    So H_CZ ∝ (I - Z_1 - Z_2 + Z_1 Z_2)
    """
    paulis = create_pauli_basis()
    I, Z = paulis['I'], paulis['Z']
    
    # Build Z_1, Z_2, Z_1 Z_2
    def pauli_at(P, target, n):
        ops = [I] * n
        ops[target] = P
        return kron_n(ops)
    
    Z1 = pauli_at(Z, q1, n_qubits)
    Z2 = pauli_at(Z, q2, n_qubits)
    Z1Z2 = Z1 @ Z2
    I_full = np.eye(2**n_qubits, dtype=complex)
    
    H_CZ = (I_full - Z1 - Z2 + Z1Z2) / 4
    return 1j * H_CZ


def create_mbqc_generators_with_cz(n_qubits):
    """
    Create MBQC generators: Paulis + CZ gates.
    
    g = <iσ_α^(k), iH_CZ^(j,k) : all qubits and pairs>
    """
    generators = create_mbqc_generators_pauli_only(n_qubits)
    
    # Add CZ Hamiltonians for all pairs
    for q1 in range(n_qubits):
        for q2 in range(q1 + 1, n_qubits):
            generators.append(create_cz_hamiltonian(q1, q2, n_qubits))
    
    return generators


def create_tgate_hamiltonian(q, n_qubits):
    """
    Create T-gate Hamiltonian.
    
    T = diag(1, e^{iπ/4}) = exp(iπ/8 (I - Z))
    So H_T ∝ (I - Z)
    """
    paulis = create_pauli_basis()
    I, Z = paulis['I'], paulis['Z']
    
    ops = [I] * n_qubits
    ops[q] = Z
    Z_q = kron_n(ops)
    I_full = np.eye(2**n_qubits, dtype=complex)
    
    # Non-Clifford angle generator
    H_T = (I_full - Z_q) / 2
    return 1j * H_T


def create_mbqc_generators_universal(n_qubits):
    """
    Create universal MBQC generators: Paulis + CZ + T.
    
    This generates full su(2^n).
    """
    generators = create_mbqc_generators_with_cz(n_qubits)
    
    # Add T-gate generators
    for q in range(n_qubits):
        generators.append(create_tgate_hamiltonian(q, n_qubits))
    
    return generators


