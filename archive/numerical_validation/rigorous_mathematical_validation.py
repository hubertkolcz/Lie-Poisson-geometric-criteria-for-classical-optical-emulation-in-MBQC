def kron_n(matrices):
    """Tensor product of list of matrices."""
    result = matrices[0]
    for m in matrices[1:]:
        result = np.kron(result, m)
    return result


def create_nqubit_pauli(pauli_string, n_qubits):
    """
    Create n-qubit Pauli operator from string like 'XYZ' or 'IXI'.
    
    Mathematical definition: P = σ_{a1} ⊗ σ_{a2} ⊗ ... ⊗ σ_{an}
    """
    paulis = create_pauli_basis()
    ops = [paulis[p] for p in pauli_string]
    return kron_n(ops)


def commutator(A, B):
    """
    Lie bracket: [A, B] = AB - BA
    
    This is the fundamental operation defining Lie algebra structure.
    """
    return A @ B - B @ A


def is_linearly_independent(new_op, basis, tol=1e-10):
    """
    Check if new operator is linearly independent of existing basis.
    
    Uses Gram-Schmidt-like projection: if ||new - proj_basis(new)|| > tol,
    then new is independent.
    """
    if len(basis) == 0:
        return np.linalg.norm(new_op) > tol
    
    # Flatten to vectors
    new_vec = new_op.flatten()
    
    # Project onto span of basis
    basis_matrix = np.array([b.flatten() for b in basis]).T
    
    # Solve least squares: find coeffs minimizing ||basis @ coeffs - new||
    coeffs, residuals, rank, s = np.linalg.lstsq(basis_matrix, new_vec, rcond=None)
    
    # Compute residual
    projection = basis_matrix @ coeffs
    residual_norm = np.linalg.norm(new_vec - projection)
    
    return residual_norm > tol


def compute_lie_algebra_basis(generators, max_iter=100, tol=1e-10):
    """
    Compute basis for Lie algebra generated by given operators.
    
    Algorithm (Lie closure):
    1. Start with generators
    2. Compute all [g_i, g_j] 
    3. Add linearly independent commutators to basis
    4. Repeat until no new elements
    
    This is a direct implementation of the mathematical definition:
    g = <{H_1, ..., H_k}>_Lie
    """
    # Initialize basis with linearly independent generators
    basis = []
    for g in generators:
        # Ensure traceless (su(n) not u(n))
        g_traceless = g - np.trace(g) / g.shape[0] * np.eye(g.shape[0], dtype=complex)
        if np.linalg.norm(g_traceless) > tol:
            if is_linearly_independent(g_traceless, basis, tol):
                basis.append(g_traceless)
    
    # Iterate commutators until closure
    iteration = 0
    while iteration < max_iter:
        new_elements = []
        n_basis = len(basis)
        
        # Compute all commutators of current basis
        for i in range(n_basis):
            for j in range(i + 1, n_basis):
                comm = commutator(basis[i], basis[j])
                
                # Check if non-zero and independent
                if np.linalg.norm(comm) > tol:
                    if is_linearly_independent(comm, basis + new_elements, tol):
                        new_elements.append(comm)
        
        # If no new elements, algebra is closed
        if len(new_elements) == 0:
            break
        
        basis.extend(new_elements)
        iteration += 1
        
        # Safety limit for exponential growth
        if len(basis) > 500:
            break
    
    return basis


def compute_dla_dimension(generators):
    """
    Compute dimension of dynamical Lie algebra.
    
    dim(g) = |basis of <generators>_Lie|
    
    This directly implements Lemma C's criterion.
    """
    basis = compute_lie_algebra_basis(generators)
    return len(basis), basis


